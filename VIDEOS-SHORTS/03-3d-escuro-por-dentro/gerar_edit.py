import os, sys
D = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(D, "..", "_template-palco3d"))
from palco import Projeto

ROT = str(__import__("pathlib").Path(__file__).resolve().parents[2] / "ROTEIROS-SHORTS" / "03 - 3D ESCURO POR DENTRO - O clique da bomba de gasolina.txt")
NAME = "03 - 3D ESCURO POR DENTRO - O clique da bomba de gasolina"
P = Projeto(D, ROT)
at, end = P.at, P.end
DUR = round(P.voz_dur + 0.6, 2)

P.param("breadcrumb", "POR DENTRO · GASOLINA", "Breadcrumb (topo)")
P.param("estrelas", 350, "Qtd. de estrelas")
P.param("fog_ini", 30, "Névoa início")
P.param("fog_fim", 75, "Névoa fim")
P.param("cor_chao", "#2a2a2e", "Cor do chão")

T_POIS, T_OLHA, T_ENQ, T_QUANDO = at("Pois"), at("Olha"), at("Enquanto"), at("Quando")
T_SEM, T_ENTAO, T_ESP, T_OTANQ = at("Sem sensor"), at("Então o clique"), at("E o espaço"), at("O tanque é")
T_ELE, T_SOQUE, T_SE, T_TUDO = at("Ele segura"), at("Só que"), at("Se o frentista"), at("Tudo isso")
T_ENTAO2, T_PAROU, T_CHEIO, T_SEGUE = at("Então, da"), at("Parou"), at("O tanque está"), at("Segue")

# eventos 3D (o cena.js lê pelo id)
P.cena("clique do bico", at("clique") + 0.25, at("clique") + 0.8, id="c_clique")
P.cena("gasolina descendo no bico", T_ENQ, T_SEM, id="c_fluxo")
P.cena("ar entrando pelo furo", at("puxando") - 0.3, at("para de entrar") + 0.2, id="c_ar")
P.cena("nível sobe e tampa o furo", at("sobe"), end("buraco") + 0.2, id="c_sobe")
P.cena("mola fecha a válvula", at("mola") + 0.1, at("mola") + 0.6, id="c_mola")
P.cena("espaço de cima pisca", at("espaço"), T_OTANQ, id="c_espaco")
P.cena("vapor tanque -> cânister", at("vapor"), T_SOQUE, id="c_vapor")
P.cena("vapor cânister -> motor", at("depois o motor"), T_SOQUE + 0.5, id="c_motor")
P.cena("líquido sobe a mangueira", at("completa"), at("encharcar") + 0.6, id="c_liquido")
P.cena("carvão encharcado", at("encharcar"), at("encharcar") + 1.6, id="c_encharca")
P.cena("tira o bico", at("tirar o bico"), at("tirar o bico") + 1.0, id="c_tira")

# câmera: alvo (cx, cy) aparece a ~42% da altura (acima da legenda); dist = distância
def F(cx, cy, dist, dx=0.25):
    return [round(cx + dx, 2), round(cy + 0.12 * dist, 2), dist], [cx, round(cy - 0.05 * dist, 2), 0]
A_WIDE = F(12.9, 1.5, 10.5)
TANK = F(0.4, 1.8, 11.5)
TUDO = F(-1.6, 1.8, 23.0)
P.cam("bomba aberta", 0, *A_WIDE, trans=0)
P.cam("bomba aproxima", T_POIS, *F(12.8, 1.7, 8.5), trans=1.4)
P.cam("ponta do bico (furinho)", T_OLHA, *F(2.35, 2.9, 3.4, 0.2), trans=1.0, drift=0.12)
P.cam("bico: gasolina + ar", T_ENQ, *F(2.45, 3.8, 5.2), drift=0.15)
P.cam("ponta: nível sobe", at("sobe") - 0.2, *F(2.4, 3.0, 4.2, 0.2), drift=0.12)
P.cam("câmara da mola", at("mola") - 0.5, *F(2.85, 6.1, 3.8, 0.15), drift=0.12)
P.cam("bico inteiro", T_SEM, *F(2.4, 4.0, 8.0))
P.cam("tanque + boca", T_ENTAO, *TANK)
P.cam("espaço de cima", T_ESP, *F(0.0, 1.6, 9.5))
P.cam("mangueira + cânister", T_OTANQ, *F(-2.9, 1.9, 14.0))
P.cam("motor", at("depois o motor"), *F(-5.8, 1.4, 11.0))
P.cam("cânister de perto", T_SOQUE, *F(-4.6, 1.45, 7.5))
P.cam("sistema inteiro", T_SE, *TUDO)
P.cam("carvão encharcando", at("encharcar") - 0.2, *F(-4.6, 1.45, 8.0))
P.cam("display da bomba", T_TUDO, *F(12.1, 2.3, 6.0))
P.cam("bomba aberta", T_ENTAO2, *A_WIDE)
P.cam("tanque cheio", T_CHEIO, *TANK)
P.cam("tudo por dentro", T_SEGUE, *TUDO)

# capítulos
P.chap("O CLIQUE", 0, T_OLHA)
P.chap("DENTRO DO BICO", T_OLHA, T_ENTAO)
P.chap("A BOCA DO TANQUE", T_ENTAO, T_OTANQ)
P.chap("O CÂNISTER", T_OTANQ, T_SE)
P.chap("SE COMPLETAR", T_SE, T_ENTAO2)
P.chap("PAROU NO CLIQUE", T_ENTAO2, T_SEGUE)
P.chap("POR DENTRO", T_SEGUE, DUR)

# rótulos / adesivos (todos na palavra falada)
s_c, s_x = at("seu carro"), at("extra")
P.rot("R$ 199,07", 0, T_OLHA, "lcd", anchor="lcd", count=[199.07, 200.00, 2], prefix="R$ ", t0=s_c, t1=s_x - s_c + 0.3)
P.rot("CLIQUE!", at("clique"), T_POIS, "tag", anchor="bicoA")
P.stk("NÃO É CHUTE", at("chute"), at("esse clique"), "amarelo", y=640)
P.stk("NÃO TEM ONDE GUARDAR", at("não tem onde"), T_OLHA, "vermelho", y=640, size=60)
P.rot("FURINHO", at("furinho"), T_ENQ, "tag", anchor="furo", dx=-150)
P.rot("PUXA AR PELO FURO", at("puxando"), T_QUANDO, "tag", anchor="tubo", dx=-120)
P.rot("GASOLINA TAMPOU O FURO", at("tampa"), at("para de entrar"), "tag", anchor="furo", dx=-60)
P.rot("AR PAROU", at("para de entrar"), at("mola"), "vermelho", anchor="furo", dx=-120)
P.rot("MOLA FECHA A VÁLVULA", at("mola"), T_SEM, "tag", anchor="mola")
P.stk("SEM SENSOR", at("Sem sensor"), T_ENTAO, "vermelho", y=600)
P.stk("SEM CHIP", at("sem chip"), T_ENTAO, "vermelho", y=740, rot=3)
P.stk("SÓ AR", at("só ar"), T_ENTAO, "verde", y=880)
P.rot("CHEGOU NA BOCA", at("chegou"), T_ESP, "tag", anchor="boca")
P.rot("ESPAÇO", at("espaço"), T_OTANQ, "tag", anchor="espaco")
P.stk("TEM DONO", at("tem dono"), T_OTANQ, "amarelo", y=640)
P.rot("MANGUEIRA", at("mangueira"), T_ELE, "tag", anchor="mangueira")
P.rot("CARVÃO", at("carvão"), at("cânister"), "tag", anchor="canister")
P.rot("CÂNISTER", at("cânister"), T_ELE, "branco", anchor="canister")
P.rot("VAPOR DA GASOLINA", at("vapor"), at("depois o motor"), "tag", anchor="mangueira")
P.rot("MOTOR QUEIMA O VAPOR", at("motor"), T_SOQUE, "tag", anchor="motor")
P.stk("FEITO PRA VAPOR", at("feito para vapor"), T_SE, "verde", y=600)
P.stk("NÃO PRA LÍQUIDO", at("não para líquido"), T_SE, "vermelho", y=740, rot=3)
P.rot("ENCHARCA O CARVÃO", at("encharcar"), at("acender"), "vermelho", anchor="canister")
P.rot("⚠ LUZ DA INJEÇÃO", at("acender"), T_TUDO, "alerta", x=540, y=620)
P.rot("CONSERTO: CENTENAS DE R$", at("conserto"), T_TUDO, "vermelho", x=540, y=780, size=56)
P.rot("R$ 200,00", T_TUDO, T_ENTAO2, "lcd", anchor="lcd")
P.stk("NÚMERO REDONDO", at("número redondo"), T_ENTAO2, "amarelo", y=640)
P.stk("AVISE O FRENTISTA", at("avise"), T_PAROU, "amarelo", y=640)
P.stk("PAROU NO 1º CLIQUE", T_PAROU, at("pode tirar"), "verde", y=640)
P.rot("PODE TIRAR O BICO", at("pode tirar"), T_CHEIO, "tag", anchor="bicoA")
P.rot("TANQUE CHEIO", at("cheio"), T_SEGUE, "verde", anchor="espaco")
P.stk("A BOMBA JÁ TE AVISOU", at("a bomba já"), T_SEGUE, "amarelo", y=640, size=60)
P.stk("SEGUE PRA VER POR DENTRO", T_SEGUE, DUR, "amarelo", y=640, size=58)

P.salvar(NAME, "3D escuro por dentro (objeto em corte)", {
    "canal": "@comofunciona.br", "canal_url": "https://www.instagram.com/comofunciona.br/",
    "video": "https://www.instagram.com/reel/DerhXbbySTz/",
    "nota": "1,5 mi views; bico da bomba em corte em estúdio escuro, breadcrumb + chip de capítulo, adesivos -4°, display LCD, legenda karaokê em caixa"},
    "cena.js", dur=DUR)
